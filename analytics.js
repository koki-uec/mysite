/* ============================================================
   analytics.js
   「サイトに何人来たか」を数えるためのファイル。

   ■ なぜ別のサービスが必要なのか
     このサイトは GitHub Pages で動いています。GitHub Pages は
     置いてあるファイルをそのまま返すだけで、プログラムを動かす場所
     （サーバー）がありません。数を数えて保存しておく場所が無いので、
     「訪問があったよ」と外部のサービスに知らせて、そこで集計して
     もらいます。ここでは GoatCounter を使います。

   ■ 見た目への影響はゼロ
     このファイルはページに何も表示しません。数字はあなただけが
     GoatCounter の管理画面にログインして確認します。
     （GoatCounter の管理画面は初期設定で非公開です）

   ■ 最初の1回だけ必要な準備
     1. https://www.goatcounter.com/signup で登録する。
        メールアドレスと「コード」を決めるだけ。無料です。
        コードは管理画面のURLになります。例：cs-page と決めたら
        ダッシュボードは https://cs-page.goatcounter.com/
     2. 下の CODE に、そのコードを書く。例： const CODE = 'cs-page';
     3. commit して push する。
     4. サイトを開いてから管理画面を見ると、1件増えています。

   ■ 自分のアクセスを数えたくないとき
     GoatCounter の管理画面 Settings → 「Ignore IP」 に自分のIPを
     登録すると、自分が見たぶんは数から外れます。
     （下の「開発中は数えない」で、パソコン内で確認しているぶんは
       もともと数えません）
------------------------------------------------------------ */

(function () {
  'use strict';

  /* ★★★ ここだけ書き換えます ★★★
     GoatCounter で決めた自分のコードを ' ' の中に入れてください。
     空のままだと、何も送らずに終わります（エラーにはなりません）。 */
  const CODE = '';

  /* --- 開発中のアクセスは数えない ----------------------------
     自分のパソコンで Live Server を使って確認しているときや、
     HTMLファイルを直接ダブルクリックで開いたときまで数えると、
     数字が自分の作業で埋まって意味が無くなります。
     そういう場所では、ここで終わりにします。
  ------------------------------------------------------------ */
  const isLocal =
    location.protocol === 'file:' ||
    location.hostname === 'localhost' ||
    location.hostname === '127.0.0.1' ||
    location.hostname === '[::1]' ||
    location.hostname === '';

  if (isLocal) return;

  /* --- コードが未設定なら、やさしく知らせて終わる ------------
     console はブラウザの開発者ツールに出るだけで、
     サイトを見に来た人には見えません。
  ------------------------------------------------------------ */
  if (!CODE) {
    console.info(
      'アクセス解析は停止中です。analytics.js の CODE に ' +
      'GoatCounter のコードを設定すると数え始めます。'
    );
    return;
  }

  /* --- GoatCounter の集計スクリプトを読み込む ----------------
     公式の貼り付けコードと同じものを、JavaScript から組み立てて
     いるだけです。こうしておくと、ページが増えても書き換えるのは
     このファイル1か所で済みます。

     ・data-goatcounter … 「どこに知らせるか」の宛先。
     ・async … このファイルの読み込みを待たずにページを表示する、
               という意味。表示が遅くなりません。
     ・読み込みに失敗しても、ページ側には何も起きません。
  ------------------------------------------------------------ */
  const s = document.createElement('script');
  s.async = true;
  s.src = 'https://gc.zgo.at/count.js';
  s.setAttribute('data-goatcounter', 'https://' + CODE + '.goatcounter.com/count');

  // 広告ブロッカー等で読めなかった場合。何もしないが、原因が分かるように残す
  s.addEventListener('error', function () {
    console.info('アクセス解析スクリプトを読み込めませんでした（数には影響しません）。');
  });

  document.head.appendChild(s);
})();
